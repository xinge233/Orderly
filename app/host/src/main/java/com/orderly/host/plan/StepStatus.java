package com.orderly.host.plan;

/** 旧版计划单步在顺序执行和逆序回滚中的状态。 */
public enum StepStatus {
    /** 尚未开始；前置步骤尚未完成或计划仍未确认。 */
    WAITING,
    /** 宿主已发起该步骤；失败后仍可能保留模块已执行的事实。 */
    RUNNING,
    /** 正向操作已成功完成，或模块报告失败但确认已产生可回滚变更。 */
    COMPLETED,
    /** 正向操作失败且模块未报告已产生变更；记录回滚时也可同步为不可恢复标记。 */
    FAILED,
    /** 对应逆向操作已完成，正向变更已按快照撤销或恢复。 */
    ROLLED_BACK
}
